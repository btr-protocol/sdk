import { describe, expect, test } from 'bun:test';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { buildDepositCalls } from '../router/index';
import { rankDeposit } from '../router/lpRoutes';
import { deposit, simulateDeposit } from './index';
import {
  cToll,
  depositShares,
  entryGapPbps,
  exposureTollPbps,
  hopSpreadPbps,
  legSpreadPbps,
  minLpOut,
  staleExcess,
} from './lpToll';

const B = (s: string) => BigInt(s);

type Hop = {
  mark: string;
  obsAge: number;
  ttl: number;
  sigmaPbps: number;
  maxDevBps: number;
  refBandBps: number;
  refObsAge: number;
  uoa: boolean;
  minFeePbps: number;
};
type Leg = {
  decimals: number;
  reserves: string;
  liabilities: string;
  invested: string;
  balance: string;
  hops: Hop[];
};
type Case = {
  name: string;
  entry: boolean;
  lower: boolean;
  baseDecimals: number;
  g: string;
  legs: Leg[];
  expected: {
    perLeg: { px: string; ok: boolean; spreadPbps: string }[];
    sweep: { tollPbps: string };
  };
  deposit: null | {
    refused: boolean;
    amt: string;
    cWad: string;
    tollPbps: string;
    indexWad: string;
    toll: string;
    face: string;
    lpAmount: string;
    deadLp: string;
  };
};
const vectors = JSON.parse(
  readFileSync(new URL('../../test/fixtures/entry-toll.json', import.meta.url), 'utf8'),
) as {
  cases: Case[];
  entryGap: { age: number; maxDevBps: number; gapPbps: string }[];
};

describe('lpToll vs the contracts (test/fixtures/entry-toll.json, generated by dex-evm)', () => {
  test('the vendored vector file is byte-identical to the one pinned', () => {
    const raw = readFileSync(new URL('../../test/fixtures/entry-toll.json', import.meta.url));
    const want = readFileSync(
      new URL('../../test/fixtures/entry-toll.sha256', import.meta.url),
      'utf8',
    ).trim();
    expect(createHash('sha256').update(raw).digest('hex')).toBe(want);
  });
  test('entryGap', () => {
    expect(vectors.entryGap.length).toBeGreaterThan(0);
    for (const v of vectors.entryGap)
      expect(entryGapPbps(BigInt(v.age), BigInt(v.maxDevBps))).toBe(B(v.gapPbps));
  });
  test('sweep tollPbps from the contract px/spread per leg', () => {
    for (const c of vectors.cases) {
      const legs = c.legs.map((l, i) => {
        const e =
          i === 0 ? { px: `${10n ** 18n}`, ok: true, spreadPbps: '0' } : c.expected.perLeg[i - 1];
        return {
          decimals: l.decimals,
          reserves: B(l.reserves),
          liabilities: B(l.liabilities),
          invested: B(l.invested),
          balance: B(l.balance),
          px: B(e.px),
          ok: e.ok,
          spreadPbps: B(e.spreadPbps),
        };
      });
      const want = B(c.expected.sweep.tollPbps);
      expect([c.name, exposureTollPbps(legs, c.baseDecimals, B(c.g), c.lower)]).toEqual([
        c.name,
        want,
      ]);
    }
  });
  test('spread derived from the hop words (non-UOA, usable legs)', () => {
    let n = 0;
    for (const c of vectors.cases) {
      c.legs.forEach((l, i) => {
        const e = c.expected.perLeg[i - 1];
        if (i === 0 || !e?.ok || l.hops.some((h) => h.uoa)) return;
        const got = legSpreadPbps(
          l.hops.map((h) => ({
            minFeePbps: BigInt(h.minFeePbps),
            staleExcessSecs: staleExcess(BigInt(h.obsAge), BigInt(h.ttl)),
            sigmaPbps: BigInt(h.sigmaPbps),
            maxDevBps: BigInt(h.maxDevBps),
            obsAgeSecs: BigInt(h.obsAge),
            refBandBps: BigInt(h.refBandBps),
            refAgeSecs: BigInt(h.refObsAge),
            uoa: false,
          })),
          c.entry,
        );
        expect([c.name, i, got]).toEqual([c.name, i, B(e.spreadPbps)]);
        n++;
      });
    }
    expect(n).toBeGreaterThan(20);
  });
  test('deposit receipt: toll, face and shares of every real deposit', () => {
    let n = 0;
    for (const c of vectors.cases) {
      const d = c.deposit;
      if (!d || d.refused) continue;
      expect(cToll(B(d.amt), B(d.tollPbps))).toBe(B(d.toll));
      const r = depositShares(B(d.amt), B(d.tollPbps), B(d.cWad), B(d.indexWad));
      expect([c.name, r.face]).toEqual([c.name, B(d.face)]);
      expect([c.name, r.shares - B(d.deadLp)]).toEqual([c.name, B(d.lpAmount)]);
      n++;
    }
    expect(n).toBeGreaterThan(5);
  });
  test('a uoa hop without the base lane is an error, never a silent zero', () => {
    const hop = {
      minFeePbps: 1n,
      staleExcessSecs: 0n,
      sigmaPbps: 0n,
      maxDevBps: 5n,
      obsAgeSecs: 0n,
      refBandBps: 0n,
      uoa: true,
    };
    expect(() => hopSpreadPbps(hop, true)).toThrow(/base/);
    expect(hopSpreadPbps(hop, false)).toBe(1000n);
  });
  test('minLpOut floors', () => {
    expect(minLpOut(10_000n, 50n)).toBe(9_950n);
  });
});

describe('depositMin plumbing', () => {
  const POOL = `0x${'11'.repeat(20)}` as `0x${string}`;
  const TOK = `0x${'22'.repeat(20)}` as `0x${string}`;
  const USER = `0x${'44'.repeat(20)}` as `0x${string}`;
  const sel = (d: string) => d.slice(0, 10);
  test('a floor selects depositMin, none keeps deposit', () => {
    const t = {
      mode: 'transfer' as const,
      token: TOK,
      amount: 1000n,
      targetToken: TOK,
      lpAmountIn: 1n,
      minLpAmountOut: 1n,
    };
    const plain = buildDepositCalls(POOL, t, { recipient: USER, needsApproval: () => false });
    const floored = buildDepositCalls(
      POOL,
      { ...t, minLpOut: 990n },
      { recipient: USER, needsApproval: () => false },
    );
    expect(sel(plain[0].data)).not.toBe(sel(floored[0].data));
    expect(floored[0].data.length).toBeGreaterThan(plain[0].data.length);
  });
  test('pool.deposit sends depositMin with a floor', async () => {
    const sent: string[] = [];
    const provider = {
      request: async ({ method, params }: { method: string; params?: unknown[] }) => {
        if (method === 'eth_sendTransaction') sent.push((params?.[0] as { data: string }).data);
        return '0xhash';
      },
    };
    await deposit(provider as never, POOL, { token: TOK, amount: 5n, minLpOut: 4n });
    await deposit(provider as never, POOL, { token: TOK, amount: 5n });
    expect(sent[0].length).toBeGreaterThan(sent[1].length);
  });
});

describe('simulateDeposit reads the minted shares off the real entrypoint', () => {
  test('the first word of DepositResult, from the caller', async () => {
    const calls: { from?: string; to?: string }[] = [];
    const word = (v: bigint) => v.toString(16).padStart(64, '0');
    const provider = {
      request: async ({ params }: { params?: unknown[] }) => {
        calls.push(params?.[0] as { from?: string });
        return `0x${word(999n)}${word(1000n)}${word(7n)}`;
      },
    };
    const USER = `0x${'44'.repeat(20)}` as `0x${string}`;
    const POOL = `0x${'11'.repeat(20)}` as `0x${string}`;
    const TOK = `0x${'22'.repeat(20)}` as `0x${string}`;
    expect(await simulateDeposit(provider as never, POOL, USER, TOK, 1000n)).toBe(999n);
    expect(calls[0].from).toBe(USER);
    expect(calls[0].to).toBe(POOL);
  });
});

describe('lpRoutes entry toll', () => {
  test('direct deposit mints (amt - toll)/C', async () => {
    const pools = [
      {
        tag: 'p',
        addr: POOL0,
        state: { base: 'USDC', legs: {}, hub: { res: 100, liab: 100, decimals: 6 } },
      },
    ] as never;
    const free = await rankDeposit(pools, 'USDC', 'USDC', 100, { slippageFrac: 0.01 });
    const tolled = await rankDeposit(pools, 'USDC', 'USDC', 100, {
      slippageFrac: 0.01,
      entryTollPbps: 10_000,
    });
    expect(tolled.best?.out).toBeCloseTo((free.best?.out ?? 0) * 0.99, 9);
  });
});
const POOL0 = `0x${'11'.repeat(20)}` as `0x${string}`;
